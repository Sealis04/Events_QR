import type { BaseSQLiteDatabase } from "drizzle-orm/sqlite-core";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sqliteSchema } from "@events-qr/core";

/** Synchronous drizzle SQLite database: better-sqlite3 under Node, bun:sqlite under Bun. */
export type HubRunResult = { changes: number; lastInsertRowid: number | bigint };
export type HubDb = BaseSQLiteDatabase<"sync", HubRunResult, typeof sqliteSchema>;

/** The part of the two drivers' connections the hub uses. */
export interface SqliteHandle {
  exec(sql: string): unknown;
  close(): void;
  /** `transaction(fn).immediate()` is `BEGIN IMMEDIATE ... COMMIT` in both drivers. */
  transaction<T>(fn: () => T): { immediate(): T };
}

export interface HubDbHandle {
  sqlite: SqliteHandle;
  db: HubDb;
  close(): void;
}

/** The SQLite migrations live in `packages/core/drizzle/sqlite` (generated by drizzle-kit). */
export const HUB_MIGRATIONS_FOLDER =
  process.env.HUB_MIGRATIONS_FOLDER ??
  resolve(dirname(fileURLToPath(import.meta.url)), "../../../../packages/core/drizzle/sqlite");

const underBun = (): boolean => !!(globalThis as { Bun?: unknown }).Bun;

/**
 * Opens the hub's SQLite file in WAL mode. Several processes use it (the web app on Node and the
 * sync worker on Bun, which cannot load better-sqlite3), so writers wait up to `busy_timeout`
 * instead of failing. `synchronous = FULL` keeps an admitted scan on disk even if the power goes
 * between the claim and the answer.
 */
export async function openHubDb(
  path: string,
  options: { migrate?: boolean; migrationsFolder?: string } = {},
): Promise<HubDbHandle> {
  if (path !== ":memory:") mkdirSync(dirname(resolve(path)), { recursive: true });
  const folder = options.migrationsFolder ?? HUB_MIGRATIONS_FOLDER;
  let sqlite: SqliteHandle;
  let db: HubDb;

  if (underBun()) {
    // Variable specifiers keep bundlers and tsc away from the Bun-only modules.
    const bunSqlite = "bun:sqlite";
    const drizzleBun = "drizzle-orm/bun-sqlite";
    const drizzleBunMigrator = "drizzle-orm/bun-sqlite/migrator";
    const { Database } = await import(/* webpackIgnore: true */ bunSqlite);
    const { drizzle } = await import(/* webpackIgnore: true */ drizzleBun);
    const connection = new Database(path);
    sqlite = connection;
    db = drizzle(connection, { schema: sqliteSchema });
    configure(sqlite);
    if (options.migrate) {
      const { migrate } = await import(/* webpackIgnore: true */ drizzleBunMigrator);
      migrate(db, { migrationsFolder: folder });
    }
  } else {
    const { default: Database } = await import("better-sqlite3");
    const { drizzle } = await import("drizzle-orm/better-sqlite3");
    const connection = new Database(path);
    sqlite = connection;
    db = drizzle(connection, { schema: sqliteSchema });
    configure(sqlite);
    if (options.migrate) {
      const { migrate } = await import("drizzle-orm/better-sqlite3/migrator");
      migrate(drizzle(connection), { migrationsFolder: folder });
    }
  }
  return { sqlite, db, close: () => sqlite.close() };
}

function configure(sqlite: SqliteHandle): void {
  sqlite.exec("PRAGMA journal_mode = WAL");
  sqlite.exec("PRAGMA busy_timeout = 5000");
  sqlite.exec("PRAGMA synchronous = FULL");
  sqlite.exec("PRAGMA foreign_keys = ON");
}
