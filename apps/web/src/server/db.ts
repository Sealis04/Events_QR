import { drizzle, type MySql2Database } from "drizzle-orm/mysql2";
import { migrate } from "drizzle-orm/mysql2/migrator";
import { createPool, type Pool } from "mysql2/promise";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { mysqlSchema } from "@events-qr/core";
import type { Config } from "./config";

export type Db = MySql2Database<typeof mysqlSchema>;

export interface DbHandle {
  db: Db;
  pool: Pool;
  close(): Promise<void>;
}

export interface DbSettings {
  host: string;
  port: number;
  database: string;
  user: string;
  password: string;
  poolSize?: number;
}

export function dbSettings(config: Config): DbSettings {
  return {
    host: config.DB_HOST,
    port: config.DB_PORT,
    database: config.DB_NAME,
    user: config.DB_USER,
    password: config.DB_PASSWORD,
    poolSize: config.DB_POOL_SIZE,
  };
}

export function connectDb(settings: DbSettings): DbHandle {
  const pool = createPool({
    host: settings.host,
    port: settings.port,
    database: settings.database,
    user: settings.user,
    password: settings.password,
    connectionLimit: settings.poolSize ?? 20,
    // bigint columns hold Unix seconds; drizzle converts them to numbers.
    supportBigNumbers: true,
    bigNumberStrings: true,
    timezone: "Z",
  });
  const db = drizzle(pool, { schema: mysqlSchema, mode: "default" });
  return { db, pool, close: () => pool.end() };
}

/** The MariaDB migrations live in `packages/core/drizzle/mysql` (generated by drizzle-kit). */
export const MIGRATIONS_FOLDER =
  process.env.MIGRATIONS_FOLDER ??
  resolve(dirname(fileURLToPath(import.meta.url)), "../../../../packages/core/drizzle/mysql");

export async function runMigrations(db: Db, folder: string = MIGRATIONS_FOLDER): Promise<void> {
  await migrate(db, { migrationsFolder: folder });
}
